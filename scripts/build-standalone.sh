#!/usr/bin/env bash
# Bundles bin/update-all + lib/*.sh into a single standalone dist/update-all file
# so Linux users can download and run a single portable Bash script if desired.
set -euo pipefail

repo_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out_file="${1:-$repo_dir/dist/update-all}"
out_dir="$(dirname "$out_file")"

mkdir -p -- "$out_dir"

tmp_file="$(mktemp "${out_dir}/.update-all.tmp.XXXXXX")"
trap 'rm -f -- "$tmp_file"' EXIT

in_loader=0
marker_seen=0
line_num=0

{
  printf '#!/usr/bin/env bash\n'
  printf '# Standalone single-file build of update-all (generated by scripts/build-standalone.sh).\n'
  printf '# Public-safe: no secrets or machine-specific paths.\n'

  while IFS= read -r line || [ -n "$line" ]; do
    line_num=$((line_num + 1))
    if [ "$line_num" -eq 1 ] && [ "$line" = '#!/usr/bin/env bash' ]; then
      continue
    fi
    if [ "$line" = '# __UA_BUNDLE_LOADER_BEGIN__' ]; then
      in_loader=1
      continue
    fi
    if [ "$line" = '# __UA_BUNDLE_MODULES_HERE__' ]; then
      in_loader=0
      marker_seen=1
      printf '_UA_BUNDLED=1\n\n'
      for mod in \
        colors_and_glyphs.sh \
        tui.sh \
        runner.sh \
        discover.sh \
        updaters.sh \
        cleanup.sh \
        safety_coach.sh \
        receipt.sh; do
        printf '# ===== MODULE: lib/%s =====\n' "$mod"
        sed '1{/^#!\/usr\/bin\/env bash$/d;}' "$repo_dir/lib/$mod"
        printf '\n'
      done
      continue
    fi
    if [ "$in_loader" -eq 0 ]; then
      printf '%s\n' "$line"
    fi
  done < "$repo_dir/bin/update-all"
} > "$tmp_file"

if [ "$marker_seen" -ne 1 ]; then
  printf 'build-standalone.sh: missing # __UA_BUNDLE_MODULES_HERE__ marker in bin/update-all\n' >&2
  exit 1
fi

chmod +x "$tmp_file"
bash -n "$tmp_file"
mv -f -- "$tmp_file" "$out_file"
printf 'Built standalone bundle -> %s (%s lines)\n' "$out_file" "$(wc -l < "$out_file" | tr -d ' ')"
